from pathlib import Path
import numpy as np
import pandas as pd
import torch
from sklearn.preprocessing import normalize
from scipy.sparse import csr_matrix

ROOT = Path(".")
DATA = ROOT / "processed/lastfm_cold"
E2 = ROOT / "results/e2_cold_start"
OUT = ROOT / "results/e3_controllability"
OUT.mkdir(parents=True, exist_ok=True)

SEED = 42
K = 20
ANCHORS = 20
LAMBDAS = [0.0, 0.1, 0.25, -1.0]
TARGET_SATISFACTION = 0.80
SEARCH_LAMBDAS = np.linspace(0.0, 1.0, 101)

CONTROLS = {
    "rock": 73,
    "electronic": 18,
    "pop": 24,
    "indie": 81,
    "metal": 1,
    "jazz": 83,
    "ambient": 14,
    "acoustic": 185,
}

# Load only the checkpoint generated by your own trusted script.
ckpt = torch.load(
    E2 / "mf_bpr_checkpoint.pt",
    map_location="cpu",
    weights_only=False
)

U = ckpt["model_state"]["user_emb.weight"].numpy()
V = ckpt["model_state"]["item_emb.weight"].numpy()

users = np.asarray(ckpt["users"], dtype=np.int64)
items = np.asarray(ckpt["items"], dtype=np.int64)

umap = {int(u): j for j, u in enumerate(users)}

train = pd.read_csv(DATA / "train.csv")
val = pd.read_csv(DATA / "validation.csv")

tags = pd.read_csv(
    DATA / "artist_tags_no_direct_leak.csv"
)[["item_id", "tag_id"]].drop_duplicates()

cold = np.sort(val.item_id.unique())
candidate_ids = np.concatenate([items, cold])
cmap = {int(x): j for j, x in enumerate(candidate_ids)}

assert len(set(candidate_ids)) == len(candidate_ids)

# Build artist-tag matrix.
all_items = candidate_ids
all_tags = np.sort(tags.tag_id.unique())

imap = {int(x): j for j, x in enumerate(all_items)}
tmap = {int(x): j for j, x in enumerate(all_tags)}

tags = tags[
    tags.item_id.isin(imap) &
    tags.tag_id.isin(tmap)
].copy()

A = csr_matrix(
    (
        np.ones(len(tags), dtype=np.float32),
        (
            tags.item_id.map(imap).to_numpy(dtype=np.int64),
            tags.tag_id.map(tmap).to_numpy(dtype=np.int64)
        )
    ),
    shape=(len(all_items), len(all_tags))
)

A.data[:] = 1.0

known_rows = np.array(
    [imap[int(i)] for i in items]
)

# Learn IDF from known training artists only.
df = np.asarray(
    (A[known_rows] > 0).sum(axis=0)
).ravel()

idf = np.log(
    (len(items) + 1) / (df + 1)
) + 1.0

A_tfidf = normalize(
    A.multiply(idf).tocsr(), axis=1
)

known_tags = A_tfidf[known_rows]

# Transfer the existing semantic-weighted anchor representation.
sims = (
    A_tfidf[
        [imap[int(i)] for i in cold]
    ] @ known_tags.T
).tocsr()

cold_vecs = []

for j in range(len(cold)):
    row = sims.getrow(j)

    if row.nnz == 0:
        cold_vecs.append(
            np.zeros(V.shape[1], dtype=np.float32)
        )
        continue

    order = np.argsort(
        -row.data, kind="stable"
    )[:ANCHORS]

    idx = row.indices[order]
    weights = row.data[order]

    w = np.exp(weights - weights.max())
    w /= w.sum()

    cold_vecs.append(
        (V[idx] * w[:, None]).sum(axis=0)
    )

cold_vecs = np.asarray(
    cold_vecs, dtype=np.float32
)

C = np.vstack([V, cold_vecs])

# Cosine-calibrated base scores.
U_normalized = normalize(U, axis=1)
C_normalized = normalize(C, axis=1)

base_scores = U_normalized @ C_normalized.T

# User training histories.
seen = {}

for u, i in zip(train.user_id, train.item_id):
    seen.setdefault(int(u), set()).add(int(i))

# Validation targets only.
targets = {}

for u, i in zip(val.user_id, val.item_id):
    if int(u) in umap:
        targets.setdefault(int(u), set()).add(int(i))

eval_users = sorted(targets)
eval_indices = np.asarray(
    [umap[u] for u in eval_users]
)

base_scores = base_scores[eval_indices].copy()

# Remove already-listened-to training artists.
for row_idx, u in enumerate(eval_users):
    for item in seen.get(u, set()):
        j = cmap.get(item)
        if j is not None:
            base_scores[row_idx, j] = -np.inf

# Metadata-based control indicators.
tag_indicators = {}

for name, tag_id in CONTROLS.items():
    if tag_id not in tmap:
        raise ValueError(
            f"Control {name} ({tag_id}) absent from metadata"
        )

    tag_indicators[name] = (
        A[:, tmap[tag_id]]
        .toarray()
        .ravel()
        .astype(np.float32)
    )

# Deterministic top-K with item-ID tie breaking.
def recommend(scores):
    top = np.argpartition(
        -scores, kth=K - 1
    )[:K]

    order = np.lexsort(
        (candidate_ids[top], -scores[top])
    )
    return top[order]

# Cache original recommendations per user.
baseline_top = [
    recommend(base_scores[r])
    for r in range(len(eval_users))
]

discounts = 1.0 / np.log2(
    np.arange(2, K + 2)
)

records = []

for control, indicator in tag_indicators.items():
    eligible = int(indicator.sum())

    print(
        f"\nControl: {control}, "
        f"eligible artists: {eligible}",
        flush=True
    )

    for lam in LAMBDAS:
        recalls = []
        ndcgs = []
        conditional_recalls = []
        conditional_ndcgs = []
        satisfactions = []
        changes = []

        recovered_cold = set()
        exposed_artists = set()
        selected_lambdas = []
        target_met = []

        for r, u in enumerate(eval_users):
            if lam == -1.0:
                chosen = float(SEARCH_LAMBDAS[-1])
                met = False

                for candidate_lam in SEARCH_LAMBDAS:
                    trial_scores = (
                        base_scores[r]
                        + float(candidate_lam) * indicator
                    )
                    trial_top = recommend(trial_scores)

                    if (
                        indicator[trial_top].mean()
                        >= TARGET_SATISFACTION
                    ):
                        chosen = float(candidate_lam)
                        met = True
                        break
            else:
                chosen = float(lam)
                met = False

            selected_lambdas.append(chosen)
            target_met.append(met)

            scores = (
                base_scores[r] + chosen * indicator
            )

            top = recommend(scores)
            recommended = candidate_ids[top]

            relevant = targets[u]
            hits = np.asarray(
                [int(i in relevant) for i in recommended],
                dtype=np.float32
            )

            recall = hits.sum() / len(relevant)

            # Relevant validation artists matching this control.
            matching_relevant = {
                i for i in relevant
                if indicator[cmap[i]] > 0
            }

            if matching_relevant:
                matching_hits = np.asarray(
                    [
                        int(i in matching_relevant)
                        for i in recommended
                    ],
                    dtype=np.float32
                )

                conditional_recalls.append(
                    float(
                        matching_hits.sum()
                        / len(matching_relevant)
                    )
                )

                conditional_dcg = np.sum(
                    matching_hits * discounts
                )

                conditional_idcg = discounts[
                    :min(K, len(matching_relevant))
                ].sum()

                conditional_ndcgs.append(
                    float(
                        conditional_dcg / conditional_idcg
                    )
                )

            dcg = np.sum(hits * discounts)
            idcg = discounts[
                :min(K, len(relevant))
            ].sum()

            recalls.append(float(recall))
            ndcgs.append(float(dcg / idcg))

            satisfactions.append(
                float(indicator[top].mean())
            )

            original = set(
                candidate_ids[baseline_top[r]]
            )

            changes.append(
                1.0 - len(
                    original & set(recommended)
                ) / K
            )

            exposed_artists.update(
                int(i) for i in recommended
            )

            recovered_cold.update(
                int(i) for i in recommended
                if i in relevant
            )

        records.append({
            "control": control,
            "lambda": lam,
            "policy": (
                "adaptive_80"
                if lam == -1.0
                else f"fixed_{lam}"
            ),
            "MeanSelectedLambda": float(
                np.mean(selected_lambdas)
            ),
            "TargetMetFraction": (
                float(np.mean(target_met))
                if lam == -1.0 else np.nan
            ),
            "Recall@20": float(np.mean(recalls)),
            "NDCG@20": float(np.mean(ndcgs)),
            "ConditionalRecall@20": (
                float(np.mean(conditional_recalls))
                if conditional_recalls else np.nan
            ),
            "ConditionalNDCG@20": (
                float(np.mean(conditional_ndcgs))
                if conditional_ndcgs else np.nan
            ),
            "ConditionalUsers": len(conditional_recalls),
            "ControlSatisfaction@20": float(
                np.mean(satisfactions)
            ),
            "ChangedItems@20": float(
                np.mean(changes)
            ),
            "RecoveredColdArtists": len(recovered_cold),
            "ExposedArtists": len(exposed_artists),
            "EligibleArtists": eligible,
            "EvaluationUsers": len(eval_users)
        })

results = pd.DataFrame(records)

output = OUT / "adaptive_baseline_validation.csv"
results.to_csv(output, index=False)

print("\n=== E3 VALIDATION RESULTS ===")

print(
    results[
        [
            "control",
            "lambda",
            "Recall@20",
            "NDCG@20",
            "ConditionalRecall@20",
            "ConditionalNDCG@20",
            "ConditionalUsers",
            "ControlSatisfaction@20",
            "ChangedItems@20",
            "RecoveredColdArtists"
        ]
    ].round(4).to_string(index=False)
)

print("\nSaved:", output)
